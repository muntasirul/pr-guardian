"""Build the results.md cost/quality table from harness output."""

from __future__ import annotations

COLUMNS = [
    ("system", "System"),
    ("n", "N"),
    ("valid_output_rate", "Valid %"),
    ("accuracy", "Accuracy"),
    ("macro_f1", "Macro F1"),
    ("pr_auc", "PR-AUC"),
    ("avg_latency_ms", "Avg latency (ms)"),
    ("est_cost_per_1k_diffs", "Est $ / 1k diffs"),
]


def _fmt(value, key):
    if value is None:
        return "-"
    if key in ("valid_output_rate", "accuracy", "macro_f1", "pr_auc"):
        return f"{value * 100:.1f}" if isinstance(value, (int, float)) and value <= 1 else str(value)
    if key == "est_cost_per_1k_diffs":
        return f"${float(value):.2f}"
    return str(value)


def build_markdown(results: list[dict]) -> str:
    lines = [
        "# PR Guardian — Evaluation Results",
        "",
        "Quality and estimated cost per system on the held-out test split.",
        "Cost figures are estimates from token counts and public list prices; see the",
        "harness code for the assumptions.",
        "",
    ]
    header = "| " + " | ".join(label for _, label in COLUMNS) + " |"
    sep = "|" + "|".join("---" for _ in COLUMNS) + "|"
    lines += [header, sep]
    for r in results:
        if r.get("skipped"):
            lines.append(f"| {r.get('system', '?')} | skipped: {r['skipped']} |" + " |" * (len(COLUMNS) - 2))
            continue
        lines.append("| " + " | ".join(_fmt(r.get(k), k) for k, _ in COLUMNS) + " |")
    lines += ["", "_Generated by `python -m eval.harness`._"]
    return "\n".join(lines) + "\n"
